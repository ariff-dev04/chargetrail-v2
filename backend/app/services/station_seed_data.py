def build_malaysian_seed_dataset() -> list[StationCreate]:
    """Construct 14 verified Malaysian EV station locations across Peninsular Malaysia."""
    stations: list[StationCreate] = []
    for item in _RAW_STATIONS:
        plugs = [PlugInfo(type=p[0], power_kw=p[1], count=p[2]) for p in item["plugs"]]
        steps = [
            AccessStep(step_number=i + 1, instruction=instruction)
            for i, instruction in enumerate(item["steps"])
        ]
        stations.append(
            StationCreate(
                name=item["name"],
                operator_name=item["operator"],
                address=item["address"],
                city=item["city"],
                state=item["state"],
                latitude=item["lat"],
                longitude=item["lng"],
                plug_types=plugs,
                max_power_kw=item["max_kw"],
                is_available=True,
                is_24_hours=item["is_24h"],
                operation_hours=item["hours"],
                charging_cost_myr=item["cost"],
                parking_fee_myr=item["parking"],
                parking_level=item["level"],
                amenities=item["amenities"],
                how_to_access=steps,
                source="community",
                is_verified=True,
            )
        )
    return stations
